import 'dart:io';
void main() {
  print('Четные числа от 1 до 20:');

  for (int i = 1; i <= 20; i++) {
    if (i % 2 != 0) {
      continue;
    }

    print(i);
  }
}



Цикл for проверяет числа от 1 до 20. Если число отрицательное, срабатывает continue-
оно пропускается и так на экране идут только правильные числа.